/**
 * 问题流定义：一屏一题。
 *
 * 设计原则：
 * - 只有年龄和性别必答，其余都能「跳过/不确定」——不确定一律不触发高危条件，绝不因不确定而升档。
 * - 每个选项都用大白话，术语第一次出现必须解释（"包年"、"一级亲属"）。
 * - 依赖题：只有选了「是」才展开，避免一上来就一堆题。
 *
 * 词表（全站只有这三种"不知道"，一种说法只对应一个值，validate 会拦：
 * ------------------------------------------------------------------
 *   unknown   真的不知道 / 记不清 / 没查过      → 界面写「不确定」「记不清」「没查过」
 *   declined  知道，但不想说                    → 界面只写「不方便说」
 *   阴性值     明确没有                         → 界面写「不是」「都没有」
 *
 * 为什么必须分开：这两件事对结果的影响完全不同。「不确定」是可以补的（翻报告、
 * 问家人），补完之后清单会变；「不方便说」是你的权利，产品要做的是承认清单因此
 * 不完整，而不是假装它完整。合并成一个值，结果页就只能说一句含糊的"部分项目未包含"。
 */

/* 「是 / 不是」型题（吸烟、二手烟、职业粉尘、油烟这类）
 *
 * 这里装的是「不方便说」，<b>不是</b>「不确定」。老板 2026-11-20 拍板：
 * 你自己抽不抽烟、家里有没有人抽，不存在"不知道"，只有"不想说"。
 * 原来给「不确定」等于替他承认"我不知道自己抽不抽烟"，既荒谬，又会让
 * "不确定"和"不方便说"这两个完全不同的东西混成一个按钮。
 */
