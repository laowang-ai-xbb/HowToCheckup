// 名字里不要再挂"（与医生商量）"：B 档的标题已经叫「你来定」，
// 每个卡片名再重复一遍，等于一句话说三遍。
const strip = (s) => String(s).replace(/（与医生(商量|商议)）$/, '');

let hit = 0;
for (const rule of doc.rules) {
  const p = PATCH[rule.id];
  if (!p) continue;
  if (rule.category !== 'B') throw new Error(`${rule.id} 不是 B 档，补丁表写错了`);
  rule.lean = p.lean;
  rule.leanNote = p.leanNote;
  rule.verdict = p.verdict;
  rule.name = strip(rule.name);
  hit++;
}

if (hit !== Object.keys(PATCH).length) {
  throw new Error(`补丁表 ${Object.keys(PATCH).length} 条，只命中 ${hit} 条，请核对 id`);
}

doc.updatedAt = new Date().toISOString().slice(0, 10);
writeFileSync(P, JSON.stringify(doc, null, 2) + '\n', 'utf8');
console.log(`已为 ${hit} 条 B 档规则补上 lean / leanNote，并改写 verdict`);
